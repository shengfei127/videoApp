import { expect, test, type Page } from '@playwright/test'

async function createLearningCourse(page: Page, scenario: 'library' | 'resume' = 'library'): Promise<void> {
  await page.clock.install({ time: new Date(2026, 9, 27, 12) })
  await page.goto(`/?scenario=${scenario}#/pages/home/index`, { waitUntil: 'domcontentloaded' })
  await page.locator('.bottom-nav').getByLabel('设置').click()
  await page.locator('.settings-menu-row').filter({ hasText: '每日课程' }).click()
  await page.getByRole('switch', { name: '每日解锁课程' }).click()
  await page.getByTestId('daily-unlock-manage').click()
  await page.getByTestId('mode-videos').click()
  await page.getByTestId('course-name').locator('input').fill('旅行学习计划')
  await page.locator('[data-video-id="baidu:1001"]').click()
  await page.locator('[data-video-id="baidu:700000000000000003"]').click()
  await page.locator('[data-video-id="direct:00000000-0000-4000-8000-000000000001"]').click()
  await expect(page.getByTestId('episode-preview')).toContainText('1. 第2站·海边.mp4')
  await expect(page.getByTestId('episode-preview')).toContainText('2. 第10站·山间.mp4')
  await expect(page.locator('.daily-plan-hint').filter({ hasText: '每天开放 1 集' })).toBeVisible()
  await expect(page.getByTestId('schedule-preview')).toContainText('今天')
  await expect(page.getByTestId('schedule-preview')).toContainText('明天')
  await page.getByTestId('create-course').click()
  await expect(page.getByTestId('course-card')).toContainText('已开放 1 / 3 集')
  await expect(page.getByTestId('course-name')).toHaveCount(0)
  await expect(page.getByTestId('new-course')).toBeVisible()
  await page.getByLabel('返回设置', { exact: true }).click()
  await page.locator('.bottom-nav').getByLabel('首页').click()
}

test('learning home supports backlog, completion undo, tomorrow preview, and editable plans', async ({ page }, testInfo) => {
  await createLearningCourse(page)
  const today = page.locator('[data-home-section="today"]')
  const sea = page.locator('[data-lesson-id="baidu:1001"]')
  await expect(sea).toContainText('约 26 分钟')
  await expect(today).toContainText('剩余约 26 分钟')
  const originalHistory = await page.evaluate(() => (window as any).uni.getStorageSync('pianke:progress:v1'))
  await sea.getByTestId('lesson-more').click()
  await sea.getByLabel('标记学完：第2站·海边.mp4', { exact: true }).click()
  expect(await page.evaluate(() => (window as any).uni.getStorageSync('pianke:progress:v1'))).toEqual(originalHistory)
  await expect(page.locator('[data-home-section="recent"]')).toHaveCount(0)
  await expect(today).toContainText('今日学习已完成')
  await expect(sea.getByText('复习本节', { exact: true })).toBeVisible()
  await sea.getByTestId('lesson-more').click()
  await sea.getByLabel('撤销学完：第2站·海边.mp4', { exact: true }).click()
  await expect(page.locator('.home-learning-done')).toHaveCount(0)
  await expect(sea).toContainText('开始学习')
  await page.clock.fastForward(24 * 60 * 60 * 1000)
  await expect(today).toContainText('旅行学习计划 · 第 2 集')
  await expect(page.getByTestId('backlog-lessons')).toHaveCount(0)
  await page.locator('[data-backlog-course]').filter({ hasText: '旅行学习计划 · 待补学 1 节' }).click()
  await expect(page.getByTestId('backlog-lessons')).toContainText('第2站·海边.mp4')
  await sea.getByTestId('lesson-more').click()
  await sea.getByLabel('标记学完：第2站·海边.mp4', { exact: true }).click()
  await expect(sea).toHaveCount(0)
  await expect(page.getByTestId('learning-undo')).toContainText('第2站·海边.mp4')
  const undoLayout = await page.getByTestId('learning-undo').evaluate((element) => {
    const bounds = element.getBoundingClientRect()
    const nav = document.querySelector('.bottom-nav')!.getBoundingClientRect()
    return { position: getComputedStyle(element).position, top: bounds.top, bottom: bounds.bottom, left: bounds.left, right: bounds.right, navTop: nav.top, viewportWidth: window.innerWidth, viewportHeight: window.innerHeight }
  })
  expect(undoLayout.position).toBe('fixed')
  expect(undoLayout.top).toBeGreaterThanOrEqual(0)
  expect(undoLayout.left).toBeGreaterThanOrEqual(0)
  expect(undoLayout.right).toBeLessThanOrEqual(undoLayout.viewportWidth)
  expect(undoLayout.bottom).toBeLessThanOrEqual(undoLayout.viewportHeight)
  expect(undoLayout.bottom).toBeLessThanOrEqual(undoLayout.navTop)
  await page.getByTestId('learning-undo').locator('uni-button, button').filter({ hasText: '撤销' }).click()
  await expect(page.getByTestId('backlog-lessons')).toContainText('第2站·海边.mp4')
  await expect(page.getByTestId('learning-undo')).toHaveCount(0)
  expect(await page.evaluate(() => (window as any).uni.getStorageSync('pianke:progress:v1'))).toEqual(originalHistory)
  await expect(page.locator('[data-lesson-id="baidu:700000000000000003"]')).toContainText('约 24 分钟')
  await page.locator('.home-learning-disclosure').filter({ hasText: '查看明日安排' }).click()
  await expect(page.getByTestId('tomorrow-lessons')).toContainText('示例直播流')
  await expect(page.getByTestId('tomorrow-lessons').locator('button')).toHaveCount(0)
  await expect(page.locator('[data-home-section="recent"] .video-row')).toHaveCount(0)
  await page.clock.runFor(2_000)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: testInfo.outputPath('learning-home-backlog.png'), fullPage: true })

  await page.locator('[data-lesson-id="baidu:700000000000000003"]').getByTestId('lesson-more').click()
  await page.locator('[data-lesson-id="baidu:700000000000000003"]').getByLabel('标记学完：第10站·山间.mp4', { exact: true }).click()
  await expect(today).toContainText('今日学习已完成')
  await page.clock.runFor(2_000)
  await page.screenshot({ path: testInfo.outputPath('learning-home-completed.png'), fullPage: true })
  await page.locator('.bottom-nav').getByLabel('设置').click()
  await page.locator('.settings-menu-row').filter({ hasText: '每日课程' }).click()
  await page.getByTestId('daily-unlock-manage').click()
  const card = page.getByTestId('course-card')
  await expect(card).toContainText('已开放 2 / 3 集')
  await expect(card).toContainText('已学完 1 / 3 集')
  await expect(page.getByTestId('course-name')).toHaveCount(0)
  await page.getByTestId('new-course').click()
  await expect(page.getByTestId('course-name')).toBeVisible()
  expect(await card.evaluate((element) => Boolean(element.compareDocumentPosition(document.querySelector('#daily-create-form')!) & Node.DOCUMENT_POSITION_FOLLOWING))).toBe(true)
  await card.getByTestId('course-more').click()
  await card.getByTestId('edit-course').click()
  await card.getByTestId('edit-course-name').locator('input').fill('轻松旅行课')
  await card.getByTestId('edit-course-count').locator('input').fill('2')
  await card.getByTestId('save-course').click()
  await expect(card).toContainText('轻松旅行课')
  await expect(card).toContainText('每天 2 集')
  await expect(card).toContainText('已开放 2 / 3 集')
  await card.getByTestId('pause-course').click()
  await expect(card).toContainText('计划已暂停')
  await page.clock.fastForward(24 * 60 * 60 * 1000)
  await expect(card).toContainText('已开放 2 / 3 集')
  await card.getByTestId('pause-course').click()
  await expect(page.getByTestId('resume-preview')).toBeVisible()
  await page.getByTestId('resume-confirm').click()
  await expect(card.getByTestId('pause-course')).toHaveText('暂停计划')
  await expect(card).toContainText('已开放 2 / 3 集')
  await page.clock.fastForward(24 * 60 * 60 * 1000)
  await expect(card).toContainText('已开放 3 / 3 集')
  await expect(card).toContainText('已学完 1 / 3 集')
})

test('an in-progress course appears once with remaining duration and its saved timestamp', async ({ page }) => {
  await createLearningCourse(page, 'resume')
  const lesson = page.locator('[data-lesson-id="baidu:1001"]')
  await expect(lesson).toContainText('继续学习')
  await expect(lesson).toContainText('剩余 20 分钟')
  await expect(lesson).toContainText('已看 6:26')
  await expect(page.locator('[aria-label="播放视频：第2站·海边.mp4"]')).toHaveCount(1)
  await expect(page.locator('.home-resume')).toHaveCount(0)
  await expect(page.locator('[data-home-section="recent"] .video-row')).toHaveCount(0)
})


test('review opens from the beginning without offering saved resume', async ({ page }) => {
  await page.route('**/rest/2.0/xpan/multimedia**', async (route) => {
    await route.fulfill({ contentType: 'application/json', body: JSON.stringify({ errno: 0, list: [{ fs_id: '1001', path: '/apps/片刻/旅行2/第2站·海边.mp4', dlink: 'https://d.pcs.baidu.com/file/review.mp4' }] }) })
  })
  await page.route('https://d.pcs.baidu.com/**', async () => { await new Promise<void>(() => {}) })
  await createLearningCourse(page, 'resume')
  const lesson = page.locator('[data-lesson-id="baidu:1001"]')
  await lesson.getByTestId('lesson-more').click()
  await lesson.getByLabel('标记学完：第2站·海边.mp4', { exact: true }).click()
  await lesson.getByText('复习本节', { exact: true }).click()
  await expect(page).toHaveURL(/restart=1/)
  const video = page.locator('video[data-testid="player-video"]')
  await expect(video).toBeVisible()
  await video.evaluate((element) => {
    const media = element as HTMLVideoElement
    Object.defineProperty(media, 'duration', { configurable: true, value: 1560 })
    media.dispatchEvent(new Event('loadedmetadata'))
  })
  await expect(page.getByRole('dialog')).toHaveCount(0)
  expect(await video.evaluate((element) => (element as HTMLVideoElement).currentTime)).toBe(0)
})
